//! Буфер обмена macOS (`NSPasteboard`).
//!
//! Уведомления о смене буфера в macOS нет: поток слежения раз в
//! [`POLL`] сверяет `changeCount` общего буфера. Свою же запись он не
//! считает новой: после записи номер версии запоминается в [`WRITTEN`].
//!
//! Чтение и запись принимают буфер параметром, чтобы тесты работали с
//! отдельным буфером (`pasteboardWithUniqueName`) и не трогали общий.

use std::sync::Arc;
use std::sync::atomic::{AtomicBool, AtomicIsize, Ordering};
use std::time::Duration;

use anyhow::{Context, Result};
use clipwire_core::{Content, FileRef};
use objc2::rc::{Retained, autoreleasepool};
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{
    NSBitmapImageFileType, NSBitmapImageRep, NSPasteboard, NSPasteboardTypeFileURL,
    NSPasteboardTypeHTML, NSPasteboardTypePNG, NSPasteboardTypeRTF, NSPasteboardTypeString,
    NSPasteboardTypeTIFF, NSPasteboardWriting, NSWorkspace,
};
use objc2_foundation::{NSArray, NSData, NSDictionary, NSString, NSURL};

use crate::i18n::{tr, trf};

/// Как часто сверять `changeCount`.
const POLL: Duration = Duration::from_millis(250);

/// `changeCount` общего буфера после нашей последней записи (-1 — не писали).
static WRITTEN: AtomicIsize = AtomicIsize::new(-1);

/// Типы, которыми менеджеры паролей (1Password, Bitwarden, KeePassXC) и
/// другие программы просят не забирать содержимое в историю:
/// <http://nspasteboard.org>. То же, что метки исключения на Windows.
const PRIVATE_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

const FILE_URL: &str = "public.file-url";
const TEXT: &str = "public.utf8-plain-text";
const PNG: &str = "public.png";
const TIFF: &str = "public.tiff";
/// Ссылка, рядом с которой браузер кладёт картинку («Скопировать изображение»).
const URL: &str = "public.url";

/// Что брать из буфера по набору типов в нём.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum Kind {
    /// Помечено как приватное.
    Excluded,
    /// Файлы и папки (Finder).
    Files,
    Image,
    /// Текст, возможно с HTML и RTF.
    Text,
    Empty,
}

/// Решить по типам буфера, что в нём. Порядок:
/// - приватная метка — ничего не брать;
/// - ссылки на файлы — файлы (Finder кладёт рядом имя текстом и иконку);
/// - картинка вместе со ссылкой (Safari, Chrome «Скопировать изображение»)
///   или без текста — картинка;
/// - иначе текст: таблицы и редакторы кладут к тексту ещё и картинку, но
///   копировали текст;
/// - картинка без текста.
pub(super) fn classify<S: AsRef<str>>(types: &[S]) -> Kind {
    let has = |t: &str| types.iter().any(|s| s.as_ref() == t);
    if PRIVATE_TYPES.iter().any(|t| has(t)) {
        return Kind::Excluded;
    }
    if has(FILE_URL) {
        return Kind::Files;
    }
    let image = has(PNG) || has(TIFF);
    let text = has(TEXT);
    if image && (has(URL) || !text) {
        return Kind::Image;
    }
    if text {
        return Kind::Text;
    }
    Kind::Empty
}

/// Следит за общим буфером, пока жив.
pub struct Watcher {
    stop: Arc<AtomicBool>,
    thread: Option<std::thread::JoinHandle<()>>,
}

impl Watcher {
    pub fn start(
        _opts: super::WatchOptions,
        mut on_change: impl FnMut(Content, Option<String>) + Send + 'static,
    ) -> Result<Self> {
        let stop = Arc::new(AtomicBool::new(false));
        let flag = stop.clone();
        let thread = std::thread::Builder::new()
            .name("clipboard-watch".into())
            .spawn(move || {
                let pb = NSPasteboard::generalPasteboard();
                // Что лежало до запуска — не новое копирование.
                let mut seen = pb.changeCount();
                while !flag.load(Ordering::Relaxed) {
                    std::thread::sleep(POLL);
                    autoreleasepool(|_| {
                        let now = pb.changeCount();
                        if now == seen {
                            return;
                        }
                        seen = now;
                        if now == WRITTEN.load(Ordering::Relaxed) {
                            tracing::debug!("буфер записан нами, пропускаю");
                            return;
                        }
                        // Программа-источник — та, что активна сейчас: буфер
                        // macOS не знает, кто в него писал.
                        let owner = frontmost_exe();
                        let seq = || pb.changeCount() as u32;
                        match super::read_consistent(seq, || read(&pb)) {
                            Some(Ok(Some(content))) => on_change(content, owner),
                            Some(Ok(None)) => {}
                            Some(Err(Skip::Excluded)) => {
                                tracing::debug!("буфер помечен как приватный, пропускаю")
                            }
                            None => tracing::debug!("буфер менялся во время чтения, пропускаю"),
                        }
                        // Если буфер сменился ещё раз во время чтения,
                        // следующий проход увидит новый номер версии.
                    });
                }
            })
            .context("не запустился поток слежения за буфером")?;
        Ok(Self {
            stop,
            thread: Some(thread),
        })
    }
}

impl Drop for Watcher {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Relaxed);
        if let Some(t) = self.thread.take() {
            let _ = t.join();
        }
    }
}

/// Почему содержимое не взяли.
#[derive(Debug)]
pub(super) enum Skip {
    Excluded,
}

fn types(pb: &NSPasteboard) -> Vec<String> {
    pb.types()
        .map(|a| a.iter().map(|t| t.to_string()).collect())
        .unwrap_or_default()
}

/// Прочитать буфер. `Ok(None)` — ничего, что мы умеем брать.
pub(super) fn read(pb: &NSPasteboard) -> Result<Option<Content>, Skip> {
    let types = types(pb);
    tracing::debug!(?types, "типы в буфере");
    Ok(match classify(&types) {
        Kind::Excluded => return Err(Skip::Excluded),
        Kind::Files => read_files(pb).map(Content::Files),
        Kind::Image => read_image(pb),
        Kind::Text => read_text(pb),
        Kind::Empty => None,
    })
}

fn read_text(pb: &NSPasteboard) -> Option<Content> {
    let text = pb
        .stringForType(unsafe { NSPasteboardTypeString })?
        .to_string();
    if text.is_empty() {
        return None;
    }
    let html = pb
        .stringForType(unsafe { NSPasteboardTypeHTML })
        .map(|s| s.to_string())
        .filter(|s| !s.trim().is_empty());
    let rtf = pb
        .dataForType(unsafe { NSPasteboardTypeRTF })
        .map(|d| d.to_vec())
        .filter(|d| !d.is_empty());
    Some(if html.is_some() || rtf.is_some() {
        Content::Rich { text, html, rtf }
    } else {
        Content::Text(text)
    })
}

/// Картинка: PNG как есть, иначе TIFF с переводом в PNG.
fn read_image(pb: &NSPasteboard) -> Option<Content> {
    let png = match pb.dataForType(unsafe { NSPasteboardTypePNG }) {
        Some(d) => d.to_vec(),
        None => tiff_to_png(&*pb.dataForType(unsafe { NSPasteboardTypeTIFF })?)?,
    };
    // Через RGBA, как на Windows: одинаковый PNG без метаданных источника.
    let img = match crate::image::decode_png(&png) {
        Ok(img) => img,
        Err(e) => {
            tracing::info!("картинку из буфера не взяли: {e:#}");
            return None;
        }
    };
    let (w, h) = img.dimensions();
    match crate::image::content_from_rgba(w, h, img.as_raw()) {
        Ok(c) => Some(c),
        Err(e) => {
            tracing::info!("картинку из буфера не взяли: {e:#}");
            None
        }
    }
}

fn tiff_to_png(tiff: &NSData) -> Option<Vec<u8>> {
    let rep = NSBitmapImageRep::imageRepWithData(tiff)?;
    let png = unsafe {
        rep.representationUsingType_properties(NSBitmapImageFileType::PNG, &NSDictionary::new())
    }?;
    Some(png.to_vec())
}

/// Файлы и папки: по ссылке `public.file-url` в каждом элементе буфера.
fn read_files(pb: &NSPasteboard) -> Option<Vec<FileRef>> {
    let items = pb.pasteboardItems()?;
    let files: Vec<_> = items
        .iter()
        .filter_map(|item| {
            let s = item.stringForType(unsafe { NSPasteboardTypeFileURL })?;
            let url = NSURL::URLWithString(&s)?;
            // Finder может положить ссылку вида file:///.file/id=…: она
            // разворачивается в обычный путь.
            let path = url.filePathURL()?.path()?;
            let mut f = super::local_file_ref(std::path::Path::new(&path.to_string()));
            // Имена в файловой системе macOS разложены (NFD: «й» — это «и» и
            // знак). Другим устройствам и поиску нужно обычное составное
            // написание (NFC); путь остаётся как есть.
            f.name = path
                .lastPathComponent()
                .precomposedStringWithCanonicalMapping()
                .to_string();
            Some(f)
        })
        .collect();
    (!files.is_empty()).then_some(files)
}

/// Полный путь исполняемого файла активной программы.
fn frontmost_exe() -> Option<String> {
    let app = NSWorkspace::sharedWorkspace().frontmostApplication()?;
    Some(app.executableURL()?.path()?.to_string())
}

/// Записать в общий буфер и запомнить его новую версию.
fn with_general(write: impl FnOnce(&NSPasteboard) -> bool) -> bool {
    autoreleasepool(|_| {
        let pb = NSPasteboard::generalPasteboard();
        let ok = write(&pb);
        WRITTEN.store(pb.changeCount(), Ordering::Relaxed);
        ok
    })
}

pub fn write_text(text: &str) -> Result<()> {
    anyhow::ensure!(
        with_general(|pb| put_text(pb, text)),
        tr("не удалось записать в буфер")
    );
    Ok(())
}

pub(super) fn put_text(pb: &NSPasteboard, text: &str) -> bool {
    pb.clearContents();
    pb.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString })
}

/// Текст вместе с HTML и RTF в одном элементе: вставляющая программа сама
/// выберет самый богатый понятный ей формат.
pub fn write_rich(text: &str, html: Option<&str>, rtf: Option<&[u8]>) -> Result<()> {
    anyhow::ensure!(
        with_general(|pb| put_rich(pb, text, html, rtf)),
        tr("не удалось записать в буфер")
    );
    Ok(())
}

pub(super) fn put_rich(
    pb: &NSPasteboard,
    text: &str,
    html: Option<&str>,
    rtf: Option<&[u8]>,
) -> bool {
    let mut ok = put_text(pb, text);
    if let Some(h) = html {
        ok &= pb.setString_forType(&NSString::from_str(h), unsafe { NSPasteboardTypeHTML });
    }
    if let Some(r) = rtf {
        ok &= pb.setData_forType(Some(&NSData::with_bytes(r)), unsafe { NSPasteboardTypeRTF });
    }
    ok
}

/// Картинка: PNG и TIFF (старые программы понимают только его).
pub fn write_image(png: &[u8]) -> Result<()> {
    anyhow::ensure!(
        with_general(|pb| put_image(pb, png)),
        tr("не удалось записать картинку в буфер")
    );
    Ok(())
}

pub(super) fn put_image(pb: &NSPasteboard, png: &[u8]) -> bool {
    let data = NSData::with_bytes(png);
    let tiff = NSBitmapImageRep::imageRepWithData(&data).and_then(|r| r.TIFFRepresentation());
    pb.clearContents();
    let mut ok = pb.setData_forType(Some(&data), unsafe { NSPasteboardTypePNG });
    if let Some(t) = tiff {
        ok &= pb.setData_forType(Some(&t), unsafe { NSPasteboardTypeTIFF });
    }
    ok
}

/// Положить файлы так же, как Finder: их можно вставить в Finder, в письмо,
/// в мессенджер. Пропавшие файлы — ошибка с их именами.
pub fn write_files(files: &[FileRef]) -> Result<()> {
    let missing: Vec<&str> = files
        .iter()
        .filter(|f| !std::path::Path::new(&f.path).exists())
        .map(|f| f.name.as_str())
        .collect();
    anyhow::ensure!(
        missing.is_empty(),
        trf(
            "файлов уже нет на месте: {files}",
            &[("files", &missing.join(", "))]
        )
    );
    anyhow::ensure!(
        with_general(|pb| put_files(pb, files)),
        tr("файлы не записались в буфер")
    );
    Ok(())
}

pub(super) fn put_files(pb: &NSPasteboard, files: &[FileRef]) -> bool {
    let urls: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = files
        .iter()
        .map(|f| {
            ProtocolObject::from_retained(NSURL::fileURLWithPath(&NSString::from_str(&f.path)))
        })
        .collect();
    pb.clearContents();
    pb.writeObjects(&NSArray::from_retained_slice(&urls))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn classify_by_types() {
        // Менеджеры паролей: метка рядом с обычным текстом.
        assert_eq!(
            classify(&[TEXT, "org.nspasteboard.ConcealedType"]),
            Kind::Excluded
        );
        assert_eq!(
            classify(&[TEXT, "org.nspasteboard.TransientType"]),
            Kind::Excluded
        );
        assert_eq!(
            classify(&[PNG, "org.nspasteboard.AutoGeneratedType"]),
            Kind::Excluded
        );
        // Finder: ссылка на файл, имя текстом и иконка.
        assert_eq!(classify(&[FILE_URL, TEXT, TIFF]), Kind::Files);
        // Скриншот в буфер.
        assert_eq!(classify(&[PNG]), Kind::Image);
        assert_eq!(classify(&[TIFF]), Kind::Image);
        // Браузер «Скопировать изображение»: картинка, ссылка и её текст.
        assert_eq!(classify(&[TIFF, URL, TEXT]), Kind::Image);
        // Таблица: текст, HTML и картинка — копировали текст.
        assert_eq!(
            classify(&[TEXT, "public.html", TIFF, "com.adobe.pdf"]),
            Kind::Text
        );
        // Ссылка из браузера без картинки — текст.
        assert_eq!(classify(&[URL, TEXT]), Kind::Text);
        assert_eq!(classify::<&str>(&[]), Kind::Empty);
        assert_eq!(classify(&["com.apple.unknown"]), Kind::Empty);
    }

    fn private_pb() -> Retained<NSPasteboard> {
        NSPasteboard::pasteboardWithUniqueName()
    }

    /// Удалить тестовый буфер из системы (в objc2 метода нет, он устаревший).
    fn release(pb: &NSPasteboard) {
        let _: () = unsafe { objc2::msg_send![pb, releaseGlobally] };
    }

    #[test]
    fn text_and_rich_round_trip() {
        autoreleasepool(|_| {
            let pb = private_pb();
            assert!(put_text(&pb, "привет"));
            assert_eq!(read(&pb).unwrap(), Some(Content::Text("привет".into())));

            let html = "<b>жирный</b>";
            let rtf = br"{\rtf1\ansi bold}";
            assert!(put_rich(&pb, "жирный", Some(html), Some(rtf)));
            match read(&pb).unwrap() {
                Some(Content::Rich {
                    text,
                    html: h,
                    rtf: r,
                }) => {
                    assert_eq!(text, "жирный");
                    assert_eq!(h.as_deref(), Some(html));
                    assert_eq!(r.as_deref(), Some(&rtf[..]));
                }
                other => panic!("ждали Rich, пришло {other:?}"),
            }
            release(&pb);
        });
    }

    #[test]
    fn private_marker_is_skipped() {
        autoreleasepool(|_| {
            let pb = private_pb();
            assert!(put_text(&pb, "пароль"));
            pb.setString_forType(
                &NSString::from_str(""),
                &NSString::from_str("org.nspasteboard.ConcealedType"),
            );
            assert!(matches!(read(&pb), Err(Skip::Excluded)));
            release(&pb);
        });
    }

    #[test]
    fn image_round_trip_and_tiff_only() {
        autoreleasepool(|_| {
            let rgba: Vec<u8> = (0..4 * 3 * 2).map(|i| (i * 10) as u8).collect();
            let Content::Image { png, width, height } =
                crate::image::content_from_rgba(3, 2, &rgba).unwrap()
            else {
                panic!("ждали картинку")
            };
            let pb = private_pb();
            assert!(put_image(&pb, &png));
            match read(&pb).unwrap() {
                Some(Content::Image {
                    width: w,
                    height: h,
                    ..
                }) => {
                    assert_eq!((w, h), (width, height))
                }
                other => panic!("ждали картинку, пришло {other:?}"),
            }
            // Только TIFF (так кладут картинки многие программы macOS).
            let tiff = NSBitmapImageRep::imageRepWithData(&NSData::with_bytes(&png))
                .and_then(|r| r.TIFFRepresentation())
                .unwrap();
            pb.clearContents();
            pb.setData_forType(Some(&tiff), unsafe { NSPasteboardTypeTIFF });
            match read(&pb).unwrap() {
                Some(Content::Image {
                    png: p,
                    width: w,
                    height: h,
                }) => {
                    assert_eq!((w, h), (3, 2));
                    let back = crate::image::decode_png(&p).unwrap();
                    assert_eq!(back.as_raw(), &rgba);
                }
                other => panic!("ждали картинку, пришло {other:?}"),
            }
            release(&pb);
        });
    }

    #[test]
    fn files_round_trip() {
        let dir = std::env::temp_dir().join(format!("clipwire-mac-pb-{}", uuid::Uuid::now_v7()));
        std::fs::create_dir_all(dir.join("папка")).unwrap();
        std::fs::write(dir.join("файл с пробелом.txt"), b"12345").unwrap();
        autoreleasepool(|_| {
            let refs = vec![
                super::super::local_file_ref(&dir.join("файл с пробелом.txt")),
                super::super::local_file_ref(&dir.join("папка")),
            ];
            let pb = private_pb();
            assert!(put_files(&pb, &refs));
            match read(&pb).unwrap() {
                Some(Content::Files(got)) => {
                    assert_eq!(got.len(), 2);
                    assert_eq!(got[0].name, "файл с пробелом.txt");
                    assert_eq!(got[0].size, 5);
                    assert!(!got[0].is_dir);
                    assert_eq!(got[1].name, "папка");
                    assert!(got[1].is_dir);
                    // Пути через /private/var и /var — одно и то же место.
                    let canon = |p: &str| std::fs::canonicalize(p).unwrap();
                    assert_eq!(canon(&got[0].path), canon(&refs[0].path));
                }
                other => panic!("ждали файлы, пришло {other:?}"),
            }
            release(&pb);
        });
        let _ = std::fs::remove_dir_all(dir);
    }
}
